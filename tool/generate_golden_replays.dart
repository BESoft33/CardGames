import 'dart:convert';
import 'dart:io';

import 'package:game_core/game_core.dart';
import 'package:game_twentynine/game_twentynine.dart';

/// Records complete matches of Twenty-Nine as golden replays (AGENTS.md
/// §14) and writes them to
/// `packages/game_twentynine/test/golden/replays.dart`.
///
/// The replays pin the behaviour of a released rules version (§5.7). Run
/// this only when a new rules version is introduced, never to make a failing
/// golden test pass.
///
/// Usage: `dart run tool/generate_golden_replays.dart` from the repository
/// root.
void main() {
  final replays = [
    _record('defaults', const TwentyNineConfig(), {
      'seventhCardCalled',
      'trumpChosen',
      'doubled',
      'redoubled',
      'trumpAsked',
      'pairDeclared',
      'targetMoved',
      'contractMade',
      'contractFailed',
      'firstPlayerNoPointCards',
    }),
    _record(
      'single hand',
      const TwentyNineConfig(singleHand: true, targetGamePoints: 3),
      {'singleHandDeclared', 'singleHandDeclined', 'singleHandLost'},
    ),
    _record(
      'variants',
      const TwentyNineConfig(
        direction: PlayDirection.clockwise,
        minBid: 15,
        lastTrickPoint: false,
        askTrump: AskTrumpRule.mandatory,
        allPass: AllPassRule.redeal,
        targetGamePoints: 3,
      ),
      {'allPassed', 'trumpAsked', 'pairDeclined', 'contractMade'},
    ),
    _record(
      'options off',
      const TwentyNineConfig(
        pair: false,
        doubleRedouble: false,
        seventhCard: false,
        redealChecks: false,
        targetGamePoints: 3,
      ),
      {'voided', 'contractMade', 'contractFailed'},
    ),
  ];

  final file = File('packages/game_twentynine/test/golden/replays.dart');
  file.parent.createSync(recursive: true);
  final body = replays.map(jsonEncode).join(',\n');
  file.writeAsStringSync('''
// GENERATED by tool/generate_golden_replays.dart. Do not edit by hand.
//
// Complete matches recorded with rules version ${const TwentyNineGame().rulesVersion}. If an engine change
// alters any replay, released behaviour has changed: add a new rules
// version instead of regenerating (AGENTS.md §5.7).

/// The recorded matches as JSON: rules, seed, actions and expected results.
const String goldenReplaysJson = r\'\'\'
[
$body
]
\'\'\';
''');
  stdout.writeln('Wrote ${replays.length} replays to ${file.path}');
}

const TwentyNineGame _game = TwentyNineGame();

/// Plays matches with a seeded random policy until one shows every marker
/// in [wanted]: an event name, a deal outcome, a cancel reason, or
/// `targetMoved` for a Pair that changed the target.
Map<String, Object?> _record(
  String name,
  TwentyNineConfig config,
  Set<String> wanted,
) {
  for (var attempt = 0; attempt < 100000; attempt++) {
    final nameCode = name.codeUnits.fold(0, (h, c) => h * 31 + c);
    final seed = SplitMix64(nameCode ^ attempt).next();
    final rng = Xoshiro256StarStar.seeded(seed ^ 0x5DEECE66D);
    final actions = <TwentyNineAction>[];
    var state = _game.init(config.toMatchConfig(), seed);
    final events = [...state.lastEvents];
    while (!state.isOver && actions.length < 700) {
      final legal = _game.legalActions(state, state.turn!);
      final pass = legal.whereType<Pass>();
      final action = pass.isNotEmpty && rng.nextBounded(2) == 0
          ? pass.first
          : legal[rng.nextBounded(legal.length)];
      state = _game.apply(state, action);
      actions.add(action);
      events.addAll(state.lastEvents);
    }
    if (!state.isOver) continue;
    // A Pair that moves the target, not one clamped to the bid limits,
    // so a change to the Pair rule shows up in the replay.
    int? contract;
    final markers = <String>{};
    for (final event in events) {
      markers.add(event.name);
      if (event is DealScored) markers.add(event.outcome.name);
      if (event is DealCancelled) markers.add(event.reason.name);
      if (event is AuctionWon) contract = event.contract;
      if (event is TargetChanged && event.target != contract) {
        markers.add('targetMoved');
      }
    }
    if (!markers.containsAll(wanted)) continue;
    stdout.writeln(
      '$name: attempt $attempt, ${actions.length} actions, '
      '${state.dealNumber} deals, scores ${state.scores}',
    );
    return {
      'name': name,
      'rulesVersion': _game.rulesVersion,
      'rules': config.toJson(),
      'seed': seedToHex(seed),
      'actions': [for (final action in actions) action.toJson()],
      'deals': state.dealNumber,
      'scores': state.scores,
      'winningTeam': state.winningTeam,
      'finalStateHash': state.hash,
      'eventsHash': canonicalHash([for (final e in events) e.toJson()]),
    };
  }
  throw StateError('No match for "$name" showed all of $wanted');
}
